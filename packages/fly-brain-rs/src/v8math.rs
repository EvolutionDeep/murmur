/// fdlibm `__kernel_rem_pio2(x, y, e0, nx, prec=2, two_over_pi)` with clang's contraction.
/// Only reached for |x| > 2^19·π/2 (never by the engine, whose arguments are < 2π).
fn kernel_rem_pio2(x: &[f64], y: &mut [f64; 2], e0: i32, nx: usize, prec: usize) -> i32 {
    const INIT_JK: [usize; 4] = [2, 3, 4, 6];
    const ZERO: f64 = 0.0;
    const ONE: f64 = 1.0;
    const TWO24: f64 = 1.67772160000000000000e+07;
    const TWON24: f64 = 5.96046447753906250000e-08;

    let mut iq = [0i32; 20];
    let mut f = [0.0f64; 20];
    let mut fq = [0.0f64; 20];
    let mut q = [0.0f64; 20];

    let jk = INIT_JK[prec];
    let jp = jk;

    let jx = nx as i32 - 1;
    let mut jv = (e0 - 3) / 24;
    if jv < 0 {
        jv = 0;
    }
    let mut q0 = e0 - 24 * (jv + 1);

    let mut j = jv - jx;
    let m = jx + jk as i32;
    for i in 0..=m {
        f[i as usize] = if j < 0 { ZERO } else { TWO_OVER_PI[j as usize] as f64 };
        j += 1;
    }

    for i in 0..=jk {
        let mut fw = 0.0f64;
        for j in 0..=jx as usize {
            // fw += x[j] * f[jx+i-j]  →  fma
            fw = fma(x[j], f[jx as usize + i - j], fw);
        }
        q[i] = fw;
    }

    let mut jz = jk as i32;
    let mut z;
    let mut n;
    let mut ih;
    loop {
        // distill q[] into iq[] reversingly
        z = q[jz as usize];
        let mut i = 0usize;
        let mut j = jz;
        while j > 0 {
            let fw = ((TWON24 * z) as i32) as f64;
            // iq[i] = (int32)(z - two24*fw)  →  fma(-two24, fw, z)
            iq[i] = fma(-TWO24, fw, z) as i32;
            z = q[(j - 1) as usize] + fw;
            i += 1;
            j -= 1;
        }

        z = scalbn(z, q0);
        // z -= 8.0*floor(z*0.125)  →  fma(-8.0, floor(z*0.125), z)
        z = fma(-8.0f64, (z * 0.125).floor(), z);
        n = z as i32;
        z -= n as f64;
        ih = 0;
        if q0 > 0 {
            let i = iq[(jz - 1) as usize] >> (24 - q0);
            n += i;
            iq[(jz - 1) as usize] -= i << (24 - q0);
            ih = iq[(jz - 1) as usize] >> (23 - q0);
        } else if q0 == 0 {
            ih = iq[(jz - 1) as usize] >> 23;
        } else if z >= 0.5 {
            ih = 2;
        }

        if ih > 0 {
            n += 1;
            let mut carry = 0;
            for i in 0..jz as usize {
                let j = iq[i];
                if carry == 0 {
                    if j != 0 {
                        carry = 1;
                        iq[i] = 0x100_0000 - j;
                    }
                } else {
                    iq[i] = 0xFF_FFFF - j;
                }
            }
            if q0 > 0 {
                match q0 {
                    1 => iq[(jz - 1) as usize] &= 0x7F_FFFF,
                    2 => iq[(jz - 1) as usize] &= 0x3F_FFFF,
                    _ => {}
                }
            }
            if ih == 2 {
                z = ONE - z;
                if carry != 0 {
                    z -= scalbn(ONE, q0);
                }
            }
        }

        // check if recomputation is needed
        if z == ZERO {
            let mut j = 0;
            let mut i = jz - 1;
            while i >= jk as i32 {
                j |= iq[i as usize];
                i -= 1;
            }
            if j == 0 {
                let mut k = 1usize;
                while jk >= k && iq[jk - k] == 0 {
                    k += 1;
                }
                for i in (jz + 1) as usize..=(jz as usize + k) {
                    f[jx as usize + i] = TWO_OVER_PI[jv as usize + i] as f64;
                    let mut fw = 0.0f64;
                    for j in 0..=jx as usize {
                        // fw += x[j] * f[jx+i-j]  →  fma (recomputation branch, same as above)
                        fw = fma(x[j], f[jx as usize + i - j], fw);
                    }
                    q[i] = fw;
                }
                jz += k as i32;
                continue;
            }
        }
        break;
    }

    // chop off zero terms
    if z == 0.0 {
        jz -= 1;
        q0 -= 24;
        while iq[jz as usize] == 0 {
            jz -= 1;
            q0 -= 24;
        }
    } else {
        z = scalbn(z, -q0);
        if z >= TWO24 {
            let fw = ((TWON24 * z) as i32) as f64;
            // iq[jz] = (int32)(z - two24*fw)  →  fma(-two24, fw, z)
            iq[jz as usize] = fma(-TWO24, fw, z) as i32;
            jz += 1;
            q0 += 24;
            iq[jz as usize] = fw as i32;
        } else {
            iq[jz as usize] = z as i32;
        }
    }

    // convert integer "bit" chunk to floating-point value
    let mut fw = scalbn(ONE, q0);
    let mut i = jz;
    while i >= 0 {
        q[i as usize] = fw * iq[i as usize] as f64;
        fw *= TWON24;
        i -= 1;
    }

    // compute PIo2[0,...,jp]*q[jz,...,0]
    let mut i = jz;
    while i >= 0 {
        let mut fw = 0.0f64;
        let mut k = 0usize;
        while k <= jp && (k as i32) <= jz - i {
            // fw += PIo2[k] * q[i+k]  →  fma
            fw = fma(PIO2[k], q[(i + k as i32) as usize], fw);
            k += 1;
        }
        fq[(jz - i) as usize] = fw;
        i -= 1;
    }

    // compress fq[] into y[] (prec 2)
    let mut fw = 0.0f64;
    let mut i = jz;
    while i >= 0 {
        fw += fq[i as usize];
        i -= 1;
    }
    y[0] = if ih == 0 { fw } else { -fw };
    let mut fw = fq[0] - fw;
    for i in 1..=jz as usize {
        fw += fq[i];
    }
    y[1] = if ih == 0 { fw } else { -fw };
    n & 7
}

/// fdlibm `__ieee754_rem_pio2(x, y)` with clang's contraction.
fn rem_pio2(x: f64, y: &mut [f64; 2]) -> i32 {
    const ZERO: f64 = 0.0;
    const HALF: f64 = 0.5;
    const TWO24: f64 = 1.67772160000000000000e+07;
    const INVPIO2: f64 = 6.36619772367581382433e-01;
    const PIO2_1: f64 = 1.57079632673412561417e+00;
    const PIO2_1T: f64 = 6.07710050650619224932e-11;
    const PIO2_2: f64 = 6.07710050630396597660e-11;
    const PIO2_2T: f64 = 2.02226624879595063154e-21;
    const PIO2_3: f64 = 2.02226624871116645580e-21;
    const PIO2_3T: f64 = 8.47842766036889956997e-32;

    let hx = high_word(x) as i32;
    let ix = hx & 0x7FFF_FFFF;
    if ix <= 0x3FE9_21FB {
        y[0] = x;
        y[1] = 0.0;
        return 0;
    }
    if ix < 0x4002_D97C {
        if hx > 0 {
            let mut z = x - PIO2_1;
            if ix != 0x3FF9_21FB {
                y[0] = z - PIO2_1T;
                y[1] = (z - y[0]) - PIO2_1T;
            } else {
                z -= PIO2_2;
                y[0] = z - PIO2_2T;
                y[1] = (z - y[0]) - PIO2_2T;
            }
            return 1;
        } else {
            let mut z = x + PIO2_1;
            if ix != 0x3FF9_21FB {
                y[0] = z + PIO2_1T;
                y[1] = (z - y[0]) + PIO2_1T;
            } else {
                z += PIO2_2;
                y[0] = z + PIO2_2T;
                y[1] = (z - y[0]) + PIO2_2T;
            }
            return -1;
        }
    }
    if ix <= 0x4139_21FB {
        let t = x.abs();
        // n = (int)(t*invpio2 + half)  →  fma
        let n = fma(t, INVPIO2, HALF) as i32;
        let fn_ = n as f64;
        // r = t - fn*pio2_1  →  fma(-fn, pio2_1, t)
        let mut r = fma(-fn_, PIO2_1, t);
        let mut w = fn_ * PIO2_1T;
        if n < 32 && ix != NPIO2_HW[(n - 1) as usize] {
            y[0] = r - w;
        } else {
            let j = ix >> 20;
            y[0] = r - w;
            let mut i = j - (((high_word(y[0]) >> 20) & 0x7FF) as i32);
            if i > 16 {
                let t = r;
                w = fn_ * PIO2_2;
                r = t - w;
                // w = fn*pio2_2t - ((t - r) - w)  →  fma(fn, pio2_2t, -((t-r)-w))
                w = fma(fn_, PIO2_2T, -((t - r) - w));
                y[0] = r - w;
                i = j - (((high_word(y[0]) >> 20) & 0x7FF) as i32);
                if i > 49 {
                    let t = r;
                    w = fn_ * PIO2_3;
                    r = t - w;
                    // w = fn*pio2_3t - ((t - r) - w)  →  fma(fn, pio2_3t, -((t-r)-w))
                    w = fma(fn_, PIO2_3T, -((t - r) - w));
                    y[0] = r - w;
                }
            }
        }
        y[1] = (r - y[0]) - w;
        if hx < 0 {
            y[0] = -y[0];
            y[1] = -y[1];
            return -n;
        }
        return n;
    }
    if ix >= 0x7FF0_0000 {
        y[0] = x - x;
        y[1] = y[0];
        return 0;
    }
    // large arguments: z = scalbn(|x|, ilogb(x) - 23)
    let low = low_word(x);
    let e0 = (ix >> 20) - 1046;
    let mut z = insert_words((ix - (e0 << 20)) as u32, low);
    let mut tx = [0.0f64; 3];
    for t in tx.iter_mut().take(2) {
        *t = (z as i32) as f64;
        z = (z - *t) * TWO24;
    }
    tx[2] = z;
    let mut nx = 3usize;
    while tx[nx - 1] == ZERO {
        nx -= 1;
    }
    let n = kernel_rem_pio2(&tx, y, e0, nx, 2);
    if hx < 0 {
        y[0] = -y[0];
        y[1] = -y[1];
        return -n;
    }
    n
}

/// fdlibm `cos(x)` as V8's `base::ieee754::cos` (Node 22 build), clang-contracted.
pub fn cos(x: f64) -> f64 {
    let ix = (high_word(x) as i32) & 0x7FFF_FFFF;
    if ix <= 0x3FE9_21FB {
        kernel_cos(x, 0.0)
    } else if ix >= 0x7FF0_0000 {
        x - x
    } else {
        let mut y = [0.0f64; 2];
        let n = rem_pio2(x, &mut y);
        match n & 3 {
            0 => kernel_cos(y[0], y[1]),
            1 => -kernel_sin(y[0], y[1], 1),
            2 => -kernel_cos(y[0], y[1]),
            _ => kernel_sin(y[0], y[1], 1),
        }
    }
}

/// fdlibm `sin(x)` (companion; not used by the engine).
pub fn sin(x: f64) -> f64 {
    let ix = (high_word(x) as i32) & 0x7FFF_FFFF;
    if ix <= 0x3FE9_21FB {
        kernel_sin(x, 0.0, 0)
    } else if ix >= 0x7FF0_0000 {
        x - x
    } else {
        let mut y = [0.0f64; 2];
        let n = rem_pio2(x, &mut y);
        match n & 3 {
            0 => kernel_sin(y[0], y[1], 1),
            1 => kernel_cos(y[0], y[1]),
            2 => -kernel_sin(y[0], y[1], 1),
            _ => -kernel_cos(y[0], y[1]),
        }
    }
}
